/* ═══════════════════════════════════════════════════════════════
   Lazy loader for per-module data & route-scoped UI/SQL bundles.
   window.LAZY_MANIFEST ({path: hash}) is generated by tools/stamp-assets.js,
   so every file is fetched as path?v=<hash> and can be cached as immutable.
   ═══════════════════════════════════════════════════════════════ */

window.Lazy = (() => {
  const manifest = () => window.LAZY_MANIFEST || {};
  const pending = new Map();

  function resolveStampedSrc(path) {
    if (/^https?:\/\//.test(path) || path.includes('?v=')) return path;
    const clean = path.replace(/^\/+/, '');
    const domTag = document.querySelector(`script[data-lazy][src^="${clean}"], script[data-defer][src^="${clean}"]`);
    if (domTag) {
      const attr = domTag.getAttribute('src');
      if (attr) return attr;
    }
    const hash = manifest()[clean];
    if (hash) return `${clean}?v=${hash}`;
    if (window.ASSET_VERSION) return `${clean}?v=${window.ASSET_VERSION}`;
    return clean;
  }

  function load(path, fallbackPath) {
    const cleanKey = String(path || '').replace(/^\/+/, '').split('?')[0];
    if (pending.has(cleanKey)) return pending.get(cleanKey);

    const resolvedFallback = fallbackPath || (
      path.startsWith('https://cdn.jsdelivr.net/npm/@innovatorved/code-lab')
        ? path.replace('https://cdn.jsdelivr.net/npm/', 'https://unpkg.com/')
        : path.startsWith('https://unpkg.com/@innovatorved/code-lab')
          ? path.replace('https://unpkg.com/', 'https://cdn.jsdelivr.net/npm/')
          : null
    );

    const p = new Promise((resolve, reject) => {
      const s = document.createElement('script');
      s.src = resolveStampedSrc(path);
      s.async = false;
      if (/^https?:\/\//.test(path)) s.crossOrigin = 'anonymous';
      s.onload = () => resolve();
      s.onerror = () => {
        if (resolvedFallback) {
          const fb = document.createElement('script');
          fb.src = resolvedFallback;
          fb.async = false;
          if (/^https?:\/\//.test(resolvedFallback)) fb.crossOrigin = 'anonymous';
          fb.onload = () => resolve();
          fb.onerror = () => {
            pending.delete(cleanKey);
            reject(new Error('Failed to load ' + path + ' (and fallback ' + resolvedFallback + ')'));
          };
          document.head.appendChild(fb);
          return;
        }
        pending.delete(cleanKey);
        reject(new Error('Failed to load ' + path));
      };
      document.head.appendChild(s);
    });
    pending.set(cleanKey, p);
    return p;
  }

  function loadAll(paths) {
    return Promise.all((paths || []).map(p => load(p)));
  }

  // Loads the client-side SQL workbench stack on demand (Worker-backed SQLite/Postgres + CodeMirror 6 + Visualizer)
  let _sqlStackPromise = null;
  function ensureSqlStack() {
    if (window.SqlEngine && window.TableVisualizer && window.SQL_DATASETS) {
      return Promise.resolve();
    }
    if (_sqlStackPromise) return _sqlStackPromise;
    const files = ['data/datasets.js'];
    if (typeof Worker !== 'function') {
      files.push('js/vendor/sql-wasm.js');
    }
    files.push(
      'js/sql-engine.js',
      'js/vendor/cm6-sql.js',
      'js/table-visualizer.js'
    );
    _sqlStackPromise = loadAll(files).catch(err => {
      _sqlStackPromise = null;
      throw err;
    });
    return _sqlStackPromise;
  }

  let _katexPromise = null;
  function ensureKatex() {
    if (typeof window.renderMathInElement === 'function') return Promise.resolve();
    if (_katexPromise) return _katexPromise;
    _katexPromise = loadAll([
      'js/vendor/katex/katex.min.js',
      'js/vendor/katex/auto-render.min.js'
    ]).catch(err => {
      _katexPromise = null;
      throw err;
    });
    return _katexPromise;
  }

  // Content (mNN-*.js) and questions (qNN-*.js) for a module number like "05"
  function module(number) {
    const prefixes = [`data/content/m${number}-`, `data/questions/q${number}-`];
    const files = Object.keys(manifest()).filter(f => prefixes.some(p => f.startsWith(p)));
    return Promise.all(files.map(f => load(f)));
  }

  window.loadScript = load;
  return { load, loadAll, ensureSqlStack, ensureKatex, module };
})();
